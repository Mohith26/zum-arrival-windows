// Prints every number the demo shows. Run: node scripts/report.mjs
import { simulate, pointEtas, CONSTRUCTION_FROM, fmtTime } from "../src/sim.js";
import { buildWindows, evaluate, evaluateStopTime, evaluateLate, weekly } from "../src/windows.js";
const t0 = Date.now();
const sim = simulate();
const rows = pointEtas(sim);
const win = buildWindows(rows, sim.routes);
const noAci = buildWindows(rows, sim.routes, { aci: false });
const f = (x) => (100 * x).toFixed(1) + "%";
const show = (name, e) => console.log(name.padEnd(34), "n", String(e.n).padStart(5), "| window", f(e.window.coverage), e.window.width.toFixed(2) + "m | static", f(e.static.coverage), e.static.width.toFixed(2) + "m | band", f(e.band.coverage), e.band.width.toFixed(2) + "m");
console.log("days", sim.days.length, "runs", sim.runs.length, "predictions", rows.length);
show("all test days", evaluate(win));
show("all test days (no ACI)", evaluate(noAci));
show("rainy mornings", evaluate(win, { filter: (r) => r.rain }));
const cIdx = sim.days.findIndex((d) => d >= CONSTRUCTION_FROM);
const constr = (r) => r.route === "r214" && r.stop >= 4 && r.dayIdx >= cIdx && r.dayIdx < cIdx + 10;
show("Route 214 past the lane closure, 2 wks", evaluate(win, { filter: constr }));
show("  same, no ACI", evaluate(noAci, { filter: constr }));
show("first 2 weeks (days 5-9)", evaluate(win, { fromDay: 5, filter: (r) => r.dayIdx < 10 }));
const st = evaluateStopTime(win, sim.routes);
console.log("be-at-stop (lead 8-22, n=" + st.n + "): byStop miss", f(st.byStop.miss), "wait", st.byStop.wait.toFixed(2), "| sched-5 miss", f(st.fiveEarly.miss), "wait", st.fiveEarly.wait.toFixed(2), "| eta-2 miss", f(st.etaMinus2.miss), "wait", st.etaMinus2.wait.toFixed(2), "| static miss", f(st.staticEarly.miss));
const late = evaluateLate(win, sim.routes);
console.log("late-to-bell n", late.n, "late rate", f(late.lateRate), "brier", late.brier.toFixed(4), "flag brier", late.brierFlag.toFixed(4), JSON.stringify(late.bins.map((b) => [b.n, b.predicted && +b.predicted.toFixed(3), b.observed && +b.observed.toFixed(3)])));
console.log("weekly", JSON.stringify(weekly(win, sim.days).map((w) => [w.wk, +w.window.toFixed(3), +w.static.toFixed(3), +w.band.toFixed(3)])));
const today = sim.days.length - 1;
const r214 = sim.routes.find((r) => r.id === "r214");
for (const r of win.rows.filter((x) => x.dayIdx === today && x.route === "r214" && x.stop === 4)) console.log("today stop5", fmtTime(r.issuedAt), "eta", fmtTime(r.eta), "win", fmtTime(r.lo), "-", fmtTime(r.hi), "by", fmtTime(r.byStop), "actual", fmtTime(r.actual), "sched", fmtTime(r214.stops[4].sched));
for (const r of win.rows.filter((x) => x.dayIdx === today && x.stop === sim.routes.find((y) => y.id === x.route).stops.length - 1 && x.issuedAt < 8 * 60 + 12 && x.issuedAt > 8 * 60 + 2)) console.log("today school", r.route, fmtTime(r.issuedAt), "eta", fmtTime(r.eta), "pLate", r.pLate && r.pLate.toFixed(2), "actual", fmtTime(r.actual));
console.log("ms", Date.now() - t0);
